"""Convert completed StepFun *file* ASR results into honest, timed captions.

Unlike the one-shot SSE text endpoint, /v1/audio/asr/file/query can return
utterances with start/end times if the submitted request requested them.
This module does not perform network calls, infer times, or reuse an unfinished
response as successful transcription.  Audio is not uploaded by this module.
"""
from __future__ import annotations

from .plan import Caption


class TimedASRError(ValueError):
    """Input is not a completed, timestamp-bearing StepFun file ASR result."""


def _millis(value: object, label: str) -> int:
    if type(value) is not int or not 0 <= value <= 21_600_000:
        raise TimedASRError(f"{label} must be an integer time in milliseconds")
    return value


def captions_from_step_file(payload: object, *, channel: int | None = None) -> tuple[Caption, ...]:
    """Read StepFun's `result[].utterances[]` (millisecond timestamps).

    The response is generated by the *asynchronous file* API with
    `show_utterances=true`, not the text-only HTTP SSE endpoint. In a multichannel
    response, require the caller to select a channel rather than mixing parallel
    speech into a single non-overlapping caption track. Return ordered captions
    compatible with VIDEO-Clips `captions` / standard SRT.
    """
    if not isinstance(payload, dict):
        raise TimedASRError("file ASR response must be a JSON object")
    status = payload.get("status")
    if status is not None and status not in {"SUCCESS", "SUCCEEDED", "COMPLETED"}:
        raise TimedASRError(f"ASR result is not completed (status: {status})")
    streams = payload.get("result")
    if not isinstance(streams, list) or not streams:
        raise TimedASRError("file ASR result[] missing; a text-only result has no timestamps")
    if type(channel) is not int and channel is not None:
        raise TimedASRError("channel must be a zero-based integer")
    if channel is None and len(streams) > 1:
        raise TimedASRError("multiple ASR channels; select one with --channel 0 (or 1, ...)")
    chosen = 0 if channel is None else channel
    if chosen < 0 or chosen >= len(streams):
        raise TimedASRError("channel index is out of range")
    stream = streams[chosen]
    if not isinstance(stream, dict):
        raise TimedASRError("file ASR result channel is not an object")
    utterances = stream.get("utterances")
    if not isinstance(utterances, list) or not utterances:
        raise TimedASRError("file ASR utterances are missing; submit with show_utterances=true")
    if len(utterances) > 1000:
        raise TimedASRError("too many utterances for a single VIDEO-Clips timeline")

    captions: list[Caption] = []
    for index, utterance in enumerate(utterances):
        label = f"utterances[{index}]"
        if not isinstance(utterance, dict):
            raise TimedASRError(f"{label} must be an object")
        text = utterance.get("text")
        if not isinstance(text, str) or not text.strip() or len(text) > 500:
            raise TimedASRError(f"{label}.text must be 1..500 characters")
        start = _millis(utterance.get("start_time"), label + ".start_time")
        end = _millis(utterance.get("end_time"), label + ".end_time")
        if end <= start:
            raise TimedASRError(f"{label} ends before or at its start")
        captions.append(Caption(text=text.strip(), start_ms=start, duration_ms=end - start))
    captions.sort(key=lambda c: c.start_ms)
    for previous, current in zip(captions, captions[1:]):
        if previous.end_ms > current.start_ms:
            raise TimedASRError("ASR utterances overlap on one channel; edit timestamps before importing")
    return tuple(captions)
